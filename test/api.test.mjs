import test from 'node:test';
import assert from 'node:assert/strict';
import { POST as login, GET as access, DELETE as logout } from '../app/api/access/route.js';
import { POST as token } from '../app/api/token/route.js';
import { initUsage } from '../lib/usage.mjs';
import { issueSession, COOKIE } from '../lib/auth.mjs';

test('private API rejects unauthorised requests, caps tokens, and fails closed on unbounded fitting responses', async t => {
  const oldEnv = { ...process.env }, oldFetch = globalThis.fetch;
  Object.assign(process.env, { DEMO_ACCESS_CODE: 'test-access-code', SESSION_SECRET: 'test-secret-at-least-32-characters-long', APP_ORIGIN: 'https://demo.example', FITTING_TOKEN_URL: 'https://fitting.example/session-token', FITTING_SERVER_KEY: 'test-server-key', FITTING_MODEL: 'wearon-vton', DEMO_DAILY_SESSIONS: '3' });
  globalThis.wearonUsage = initUsage(':memory:');
  t.after(() => { globalThis.fetch = oldFetch; globalThis.wearonUsage.close(); delete globalThis.wearonUsage; process.env = oldEnv; });
  let calls = 0;
  globalThis.fetch = async (url, options) => {
    calls++;
    assert.equal(url, 'https://fitting.example/session-token');
    assert.equal(options.headers.Authorization, 'Bearer test-server-key');
    const body = JSON.parse(options.body);
    assert.equal(body.expiresInSeconds, 10);
    assert.equal(body.allowedOrigin, 'https://demo.example');
    assert.equal(body.model, 'wearon-vton');
    assert.equal(body.maxSessionSeconds, 15);
    return Response.json({ token: 'scoped-test-token', maxSessionSeconds: 15 });
  };
  const request = (path, cookie = '', body, origin = 'https://demo.example') => new Request(`https://demo.example/api/${path}`, { method: 'POST', headers: { origin, cookie, 'content-type': 'application/json' }, body });
  assert.equal((await token(request('token'))).status, 401);
  assert.equal((await token(request('token', '', undefined, 'https://evil.example'))).status, 403);
  assert.equal(calls, 0);
  assert.equal((await login(request('access', '', JSON.stringify({ code: 'wrong' })))).status, 401);
  assert.equal((await login(request('access', '', 'x'.repeat(1025)))).status, 400);
  const loggedIn = await login(request('access', '', JSON.stringify({ code: 'test-access-code' })));
  assert.equal(loggedIn.status, 200);
  const cookie = loggedIn.headers.get('set-cookie');
  assert.match(cookie, /HttpOnly; SameSite=Strict/); assert.match(cookie, /Secure/);
  assert.equal((await (await access(request('access', cookie))).json()).unlocked, true);
  const good = await token(request('token', cookie));
  assert.equal(good.status, 200); assert.equal((await good.json()).duration, 15);
  assert.equal(good.headers.get('cache-control'), 'no-store');
  assert.equal((await token(request('token', cookie))).status, 429);
  const freshCookie = () => `${COOKIE}=${issueSession(process.env.SESSION_SECRET)}`;
  globalThis.fetch = async () => Response.json({ token: 'unsafe-token' });
  const unsafe = await token(request('token', freshCookie()));
  assert.equal(unsafe.status, 502); assert.equal((await unsafe.json()).token, undefined);
  globalThis.fetch = async () => { throw new Error('backend secret must never leak'); };
  const failure = await token(request('token', freshCookie()));
  assert.equal(failure.status, 502); assert.doesNotMatch(await failure.text(), /backend secret/);
  assert.equal((await token(request('token', freshCookie()))).status, 429);
  assert.match((await logout(request('access', cookie))).headers.get('set-cookie'), /Max-Age=0/);
});
